function lmeAll = plotMetricFig5FullNew( ...
    aperiodicsAll,tempsAll,dtAll,transPall,entAll, ...
    ptgroups,bandgroups,reggroups,recordinggroups,R2pmemAll, ...
    allpts,allregions,alllabels,fighinch)

params = { ...
    'Temperature', ...
    'Transition Probability', ...
    'Entropy Rate', ...
    'Dwell Time'};

nParams = numel(params);
lmeAll  = cell(nParams,1);

figwinch = 16;

figure( ...
    'Renderer','painters', ...
    'Color','w', ...
    'Units','inches', ...
    'Position',[1 1 figwinch fighinch]);

outerTL = tiledlayout(1,4, ...
    'Padding','compact', ...
    'TileSpacing','compact');

for k = 1:nParams

    % ---------------------------------------------------------
    % Create inner tiledlayout
    % ---------------------------------------------------------
    innerTL = tiledlayout(outerTL, ...
        1,1, ...
        'Padding','tight', ...
        'TileSpacing','tight');

    innerTL.Layout.Tile = k;

    title( ...
        innerTL, ...
        params{k}, ...
        'FontSize',16, ...
        'FontWeight','bold');

    % ---------------------------------------------------------
    % Select figure layout
    %
    % Narrow figure:
    %   pooled relationship only
    %
    % Wide figure:
    %   individual + heatmap / additional analyses
    % ---------------------------------------------------------
    if fighinch == 3.5

        lmeAll{k} = plotPooledAperiodicLME( ...
            innerTL, ...
            aperiodicsAll, ...
            tempsAll,dtAll,transPall,entAll, ...
            ptgroups, ...
            bandgroups, ...
            reggroups,...
            recordinggroups,...
            R2pmemAll, ...
            allpts, ...
            allregions, ...
            alllabels, ...
            params{k});

    else

        lmeAll{k} = plotHeatmapForestAperiodic( ...
            innerTL, ...
            aperiodicsAll, ...
            tempsAll,dtAll,transPall,entAll, ...
            ptgroups, ...
            bandgroups, ...
            reggroups, ...
            recordinggroups, ...
            R2pmemAll, ...
            allpts, ...
            allregions, ...
            alllabels, ...
            params{k});

    end
end

end