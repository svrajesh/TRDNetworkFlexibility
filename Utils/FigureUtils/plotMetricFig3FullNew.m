function lmeAll = plotMetricFig3FullNew( ...
    scoresAll,tempsAll,dtAll,transPall,entAll, ...
    ptgroups,bandgroups,recordinggroups,R2pmemAll,allpts,allbands,alllabels,fighinch)

params = { ...
    'Temperature', ...
    'Transition Probability', ...
    'Entropy Rate', ...
    'Dwell Time'};

nParams = numel(params);
lmeAll  = cell(nParams,1);

figwinch = 16;

figure( ...
    'Renderer','painters', ...
    'Color','w', ...
    'Units','inches', ...
    'Position',[1 1 figwinch fighinch]);

outerTL = tiledlayout(1,4, ...
    'Padding','compact', ...
    'TileSpacing','compact');

for k = 1:nParams

    % ---- create INNER tiledlayout, not axes ----
    innerTL = tiledlayout(outerTL, ...
        1, 1, ...          % dummy size; plotMetricFig3 will redefine
        'Padding','tight', ...
        'TileSpacing','tight');

    innerTL.Layout.Tile = k;

    % Optional future title hook
    title(innerTL,params{k},'FontSize',16,'FontWeight','bold')

    % ---- call Fig3 builder ----
    if fighinch == 3.5
        lmeAll{k} = plotPooledMetricLME( ...
            innerTL, ...
            scoresAll,tempsAll,dtAll,transPall,entAll, ...
            ptgroups,bandgroups,R2pmemAll,allpts,allbands, alllabels, ...
            params{k});
    else
        lmeAll{k} = plotBandsHeatmapForest( ...
            innerTL, ...
            scoresAll,tempsAll,dtAll,transPall,entAll, ...
            ptgroups,bandgroups,recordinggroups,R2pmemAll, ...
            allpts,allbands,alllabels,params{k});


    end
end
